import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { randomUUID } from 'node:crypto';

test('SPEC-018: revisar, cancelar, validar senha e excluir conta', async ({ page }) => {
  const email = `delete-${randomUUID()}@example.com`;
  const password = 'SenhaSegura123';
  await page.goto('/');
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await page.getByLabel('Nome', { exact: true }).fill('Conta Exclusão');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Criar minha conta' }).click();
  await expect(page.locator('.message[role="status"]')).toContainText('Conta criada');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar na conta' }).click();
  await page.getByRole('button', { name: 'Minha conta' }).click();
  await page.getByRole('button', { name: 'Revisar exclusão' }).click();
  await expect(page.getByText(/não pode ser desfeita/)).toBeVisible();
  const section = page.locator('section[aria-labelledby="delete-title"]');
  expect((await new AxeBuilder({ page }).include('section[aria-labelledby="delete-title"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.getByRole('button', { name: 'Cancelar exclusão' }).click();
  await expect(section.getByLabel('Senha atual')).toHaveCount(0);
  await page.getByRole('button', { name: 'Revisar exclusão' }).click();
  await section.getByLabel('Senha atual').fill('SenhaErrada123');
  await section.getByLabel('Digite EXCLUIR MINHA CONTA').fill('EXCLUIR MINHA CONTA');
  await section.getByRole('button', { name: 'Excluir conta', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('A senha atual está incorreta.');
  await section.getByLabel('Senha atual').fill(password);
  await section.getByLabel('Digite EXCLUIR MINHA CONTA').fill('EXCLUIR MINHA CONTA');
  await section.getByRole('button', { name: 'Excluir conta', exact: true }).click();
  await expect(page.locator('.message[role="status"]')).toContainText('Conta e dados excluídos.');
  await page.reload();
  await expect(page.getByRole('heading', { level: 2 })).toHaveText('Acesse sua conta');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar na conta' }).click();
  await expect(page.getByRole('alert')).toHaveText('E-mail ou senha incorretos.');
});
